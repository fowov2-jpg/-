// A paced introduction, then three different authored shift patterns. Later
// districts vary homes, wear and weather instead of requiring 999 repairs.
const SHIFTS = [
  [[0,'lights',0],[30,'leak',2],[78,'flood',1],[170,'entrance',0],[225,'roof',2],[295,'sewer',0],[355,'outage',2],[410,'door',1]],
  [[0,'door',1],[25,'sewer',0],[70,'pump',2],[145,'roof',1],[215,'lights',0],[280,'leak',2],[355,'outage',1]],
  [[0,'leak',0],[35,'entrance',1],[92,'outage',2],[160,'roof',0],[230,'pump',1],[310,'sewer',2],[385,'door',0]],
  [[0,'lights',2],[40,'roof',0],[105,'flood',1],[200,'door',2],[260,'entrance',0],[320,'leak',1],[390,'outage',0]]
];
export function shiftPlan(day,region=0,houses=3){
  const plan=SHIFTS[(day-1)%SHIFTS.length].map(([minute,kind,home])=>({minute,kind,home}));
  // Taking on more houses adds real work. Later districts create overlapping
  // calls around the major incident, so extra contracts and specialist gear
  // require a staffing decision instead of becoming free passive income.
  for(let i=0;i<Math.min(5,houses-3);i++)plan.push({minute:[80,155,245,305,365][i],kind:['leak','outage','roof','sewer','entrance'][i],home:i+3});
  if(region>=1)plan.push({minute:140,kind:'outage',home:0});
  if(region>=3)plan.push({minute:150,kind:'roof',home:2});
  if(region>=6)plan.push({minute:170,kind:'leak',home:1});
  return plan.sort((a,b)=>a.minute-b.minute);
}
